import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import type { SecretStore } from "../../../secrets/store.js";

/**
 * Where a Jira token lives (J-01).
 *
 * The original design is explicit — *"Secrets: OS keychain, never the DB"*
 * — and names Electron's `safeStorage`. This was the first use of it in
 * the repo; the interface it is used through, `SecretStore`, now lives
 * in `secrets/store.ts` with the rest of the app's keychain (KAN-126),
 * and the one `safeStorage` import site is still the composition root,
 * the discipline CLAUDE.md requires of native modules.
 *
 * The key is the OS keychain's; the ciphertext is a file under
 * `userData`. Nothing about a token touches SQLite, and nothing about it
 * crosses IPC — the renderer is told whether a repository is configured,
 * never with what.
 */

export interface CredentialsOptions {
  /** Where the ciphertext files live. `app.getPath("userData")/credentials` in production. */
  directory: string;
  store: SecretStore;
}

export type StoreResult = { ok: true } | { ok: false; reason: string };

/**
 * One file per owner, so removing one credential cannot disturb another.
 *
 * The owner is a *connection* since KAN-22, having been a repository before
 * that. The distinction matters only to callers: this has always been
 * "an opaque id names a file", which is why the move needed nothing here
 * beyond a renamed parameter.
 */
function fileFor(directory: string, ownerId: string): string {
  // Ids are UUIDv7 and generated by us, but a path is a path: anything
  // that is not a plain id is refused rather than escaped.
  if (!/^[A-Za-z0-9-]+$/.test(ownerId)) throw new Error(`refusing to build a credential path from ${JSON.stringify(ownerId)}`);
  return join(directory, `jira-${ownerId}.bin`);
}

/**
 * Stores a token for a repository.
 *
 * `isEncryptionAvailable()` is false on a Linux box with no keyring
 * (a bare container, some minimal desktops). Writing the token in the
 * clear there would quietly break the promise this module exists to
 * keep, so it refuses and says why.
 */
export function storeToken(options: CredentialsOptions, ownerId: string, token: string): StoreResult {
  if (!options.store.isEncryptionAvailable()) {
    return {
      ok: false,
      reason:
        "This machine has no OS keychain available, so EO cannot store a Jira token safely. " +
        "On Linux that usually means no keyring is running (gnome-keyring or kwallet).",
    };
  }

  mkdirSync(options.directory, { recursive: true });
  writeFileSync(fileFor(options.directory, ownerId), options.store.encryptString(token), { mode: 0o600 });
  return { ok: true };
}

/** The token, or null when the repository has none — not an error: unconfigured is a normal state. */
export function readToken(options: CredentialsOptions, ownerId: string): string | null {
  let encrypted: Buffer;
  try {
    encrypted = readFileSync(fileFor(options.directory, ownerId));
  } catch {
    return null;
  }

  try {
    return options.store.decryptString(encrypted);
  } catch {
    // Written by another machine, another OS user, or before a keychain
    // reset. Unreadable is the same as absent, and the user reconnects.
    return null;
  }
}

export function hasToken(options: CredentialsOptions, ownerId: string): boolean {
  return readToken(options, ownerId) !== null;
}

export function clearToken(options: CredentialsOptions, ownerId: string): void {
  rmSync(fileFor(options.directory, ownerId), { force: true });
}

/**
 * Moves each token from the repository that held it to the connection that
 * now does (KAN-22).
 *
 * The migration could not do this: tokens are files under `userData`,
 * not rows. Without it, everyone who had Jira connected would be asked
 * to re-enter a token they had already given us — as the price of a
 * change whose entire purpose is to stop asking twice.
 *
 * Idempotent: it skips a connection that already has a token, so running
 * it on every launch is harmless, a half-finished run finishes next
 * time, and a token rotated after the move is never overwritten by the
 * stale copy.
 *
 * It moves rather than copies. The first version kept the repository's file
 * on the grounds that deleting a working credential during an upgrade is
 * not a trade worth making — but reading the new one back first removes
 * the risk that argument rested on, and the old file has no fallback
 * value anyway: it is encrypted by the same keychain, so anything that
 * made the new one unreadable would have made it unreadable too. What is
 * left otherwise is an encrypted credential lying under userData
 * forever, that nothing reads.
 */
export function rekeyJiraTokens(options: CredentialsOptions, pairs: { repositoryId: string; connectionId: string }[]): number {
  let moved = 0;
  for (const { repositoryId, connectionId } of pairs) {
    const token = readToken(options, repositoryId);
    if (token === null) continue; // already moved, or never had one

    // Only write when the connection has nothing, so a rotation that
    // happened after an earlier run survives.
    if (readToken(options, connectionId) === null) {
      if (!storeToken(options, connectionId, token).ok) continue;
      moved += 1;
    }

    // Read back before removing anything. The old file goes only once
    // the new one demonstrably works.
    if (readToken(options, connectionId) !== null) clearToken(options, repositoryId);
  }
  return moved;
}
