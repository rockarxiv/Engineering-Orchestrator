import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { CODEWIKI } from "./catalog.js";

/**
 * What EO owes the people whose work it fetches (EO-144).
 *
 * The obligation belongs to the catalogue: this directory is what
 * decides EO downloads CodeWiki v0.2.1 at all, so it is where the proof
 * that NOTICE says so has to live. `packaging.test.ts` keeps the half
 * that is genuinely packaging's — that NOTICE is generated rather than
 * hand-edited, and that it reaches an installed app — and knows nothing
 * about what is in it, which is the same division the port draws
 * everywhere else in this subsystem.
 *
 * NOTICE itself is generated by `scripts/third-party-notice.mjs` from
 * `scripts/notice-header.md`, so anything asserted here has to be in
 * the header rather than appended to the output.
 */
const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..", "..", "..", "..", "..", "..");
const notice = readFileSync(join(repoRoot, "NOTICE"), "utf8");

describe("the attribution notice covers the binary EO fetches", () => {
  it("names it with the publisher and terms its catalogue entry carries", () => {
    // Read off the catalogue rather than retyped, so the row a person
    // reads and the terms EO shows before fetching cannot drift apart.
    for (const field of [CODEWIKI.label, CODEWIKI.publisher, CODEWIKI.termsUrl, CODEWIKI.version]) {
      expect(notice, field).toContain(field);
    }
  });

  it("carries its licence text and copyright line, not a description of them", () => {
    expect(notice).toContain("Copyright (c) 2026 0xsyncroot");
    expect(notice).toContain("Permission is hereby granted, free of charge, to any person obtaining a copy");
    expect(notice).toContain('THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND');
  });

  it("reproduces the CodeGraph attribution it itself carries", () => {
    // It is a derivative work and says so in its own NOTICE. Carrying
    // its licence while dropping who it derives from would reproduce
    // half of what it asks for.
    expect(notice).toContain("CodeGraph by Colby McHenry");
    expect(notice).toContain("https://github.com/colbymchenry/codegraph");
    // Verbatim, capitalised the way CodeGraph's own copyright line is —
    // a tidied-up copyright line is a reworded one.
    expect(notice).toContain("Copyright (c) 2026 Colby Mchenry");
  });

  it("leaves none of the four vendored grammars out", () => {
    // Upstream's own vendor/licenses/*-LICENSE files are 12-byte
    // placeholders at v0.2.1, so these come from each grammar's own
    // repository at the commit wasm-grammars.md records as vendored.
    const grammars: Array<[string, string]> = [
      ["tree-sitter-lua", "Copyright (c) 2021 Munif Tanjim"],
      ["tree-sitter-luau", "Copyright (c) 2024 polychromatist"],
      ["tree-sitter-pascal", "Copyright (c) 2018 Benjamin Gray"],
      ["tree-sitter-scala", "Copyright (c) 2018 Max Brunsfeld and GitHub"],
    ];

    for (const [grammar, copyright] of grammars) {
      expect(notice, grammar).toContain(grammar);
      expect(notice, `${grammar} copyright`).toContain(copyright);
    }
  });
});
